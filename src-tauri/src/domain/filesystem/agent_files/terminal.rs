use super::*;
use base64::Engine;
use serde::{Deserialize, Serialize};

pub const TERMINAL_FILE_OUTPUT_LIMIT: usize = 786_432;

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct FileInspection {
    pub path: String,
    pub resolved_path: String,
    pub metadata: FileMetadata,
    pub revision: String,
    pub environment: Option<FileEnvironment>,
    pub scope: String,
}
impl FileInspection {
    pub fn validate(&self, path: &str) -> FileResult<()> {
        check_file_path_syntax(path)?;
        check_file_path_syntax(&self.resolved_path)?;
        if self.path != path
            || self.revision.is_empty()
            || self.revision.len() > 128
            || self.scope.len() != 64
            || !self.scope.bytes().all(|b| b.is_ascii_hexdigit())
        {
            return Err(FileError::new(
                FileErrorKind::InvalidRequest,
                "文件检查结果未绑定当前路径或环境",
            ));
        }
        if let Some(environment) = &self.environment {
            environment.validate()?;
        }
        Ok(())
    }
}

/// These arguments are generated by the application from a consumed operation
/// ticket. They are not model tool arguments or a general shell escape hatch.
#[derive(Clone, Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct TerminalFileRequest {
    action: &'static str,
    path: String,
    nonce: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    resolved_path: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    revision: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    scope: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    approved_paths: Option<[String; 2]>,
    #[serde(skip_serializing_if = "Option::is_none")]
    options: Option<FileReadOptions>,
    #[serde(skip_serializing_if = "Option::is_none")]
    resume: Option<FilePosition>,
    offset: usize,
    limit: usize,
}
impl TerminalFileRequest {
    pub fn inspect(path: String) -> FileResult<Self> {
        check_file_path_syntax(&path)?;
        Ok(Self {
            action: "inspect",
            path,
            nonce: uuid::Uuid::new_v4().simple().to_string(),
            resolved_path: None,
            revision: None,
            scope: None,
            approved_paths: None,
            options: None,
            resume: None,
            offset: 0,
            limit: 100,
        })
    }
    pub fn read(
        inspection: &FileInspection,
        options: FileReadOptions,
        resume: Option<FilePosition>,
        sensitive_approved: bool,
    ) -> FileResult<Self> {
        options.validate()?;
        let mut request = Self::from_inspection(inspection, sensitive_approved)?;
        request.action = "read";
        request.options = Some(options);
        request.resume = resume;
        Ok(request)
    }
    pub fn list(
        inspection: &FileInspection,
        offset: usize,
        limit: usize,
        sensitive_approved: bool,
    ) -> FileResult<Self> {
        if offset >= MAX_DIRECTORY_SCAN || limit == 0 || limit > MAX_DIRECTORY_ENTRIES {
            return Err(FileError::new(
                FileErrorKind::InvalidRequest,
                "无效的目录分页范围",
            ));
        }
        let mut request = Self::from_inspection(inspection, sensitive_approved)?;
        request.action = "list";
        request.offset = offset;
        request.limit = limit;
        Ok(request)
    }
    fn from_inspection(inspection: &FileInspection, sensitive_approved: bool) -> FileResult<Self> {
        inspection.validate(&inspection.path)?;
        let sensitive =
            sensitive_file_path(&inspection.path) || sensitive_file_path(&inspection.resolved_path);
        if sensitive && !sensitive_approved {
            return Err(FileError::new(
                FileErrorKind::SensitivePath,
                "敏感路径尚未取得本次读取批准",
            ));
        }
        let mut request = Self::inspect(inspection.path.clone())?;
        request.resolved_path = Some(inspection.resolved_path.clone());
        request.revision = Some(inspection.revision.clone());
        request.scope = Some(inspection.scope.clone());
        if sensitive {
            request.approved_paths =
                Some([inspection.path.clone(), inspection.resolved_path.clone()]);
        }
        Ok(request)
    }
    pub fn nonce(&self) -> &str {
        &self.nonce
    }
    pub fn source(&self) -> String {
        let script = base64::engine::general_purpose::STANDARD.encode(include_str!("terminal.py"));
        let request = base64::engine::general_purpose::STANDARD
            .encode(serde_json::to_vec(self).expect("serializable file request"));
        // -I ignores PYTHONPATH and user startup customization; no files are
        // installed. Missing python3 produces an unavailable result at capture.
        format!("command python3 -I -c 'import base64; exec(compile(base64.b64decode(\"{script}\"), \"<ai-term-file>\", \"exec\"))' '{request}'")
    }
    pub fn parse<T: serde::de::DeserializeOwned>(&self, output: &str) -> FileResult<T> {
        if output.len() > TERMINAL_FILE_OUTPUT_LIMIT {
            return Err(FileError::new(
                FileErrorKind::Unavailable,
                "文件读取协议输出超过预算",
            ));
        }
        let prefix = format!("AI_TERM_FILE_{}_", self.nonce);
        let mut matches = output
            .lines()
            .filter_map(|line| line.trim_end_matches('\r').strip_prefix(&prefix));
        let payload = matches.next().ok_or_else(|| {
            FileError::new(
                FileErrorKind::Unavailable,
                "当前终端无法运行文件读取器（需要 Python 3），或结果协议不完整",
            )
        })?;
        if matches.next().is_some() {
            return Err(FileError::new(
                FileErrorKind::Unavailable,
                "重复的文件读取协议结果",
            ));
        }
        let data = base64::engine::general_purpose::STANDARD
            .decode(payload)
            .map_err(|_| FileError::new(FileErrorKind::Unavailable, "文件读取协议数据无效"))?;
        let value: serde_json::Value = serde_json::from_slice(&data)
            .map_err(|_| FileError::new(FileErrorKind::Unavailable, "文件读取协议结果无效"))?;
        match value.get("ok").and_then(serde_json::Value::as_bool) {
            Some(true) => serde_json::from_value(value["value"].clone()).map_err(|_| {
                FileError::new(FileErrorKind::Unavailable, "文件读取结果格式不受支持")
            }),
            Some(false) => Err(
                serde_json::from_value(value["error"].clone()).unwrap_or_else(|_| {
                    FileError::new(FileErrorKind::Unavailable, "未知的文件读取错误")
                }),
            ),
            None => Err(FileError::new(
                FileErrorKind::Unavailable,
                "文件读取结果缺少状态",
            )),
        }
    }
}
